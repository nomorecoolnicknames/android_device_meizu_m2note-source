#!/bin/sh
# check_prebuilt_kernel.sh — гейт свежести prebuilt-ядра, вызывается из
# BoardConfig.mk.  Печатает НИЧЕГО при успехе и подробное указание, что
# делать, при несовпадении; BoardConfig валит сборку, если вывод непуст.
#
# Зачем: ядро попадает в образ через TARGET_PREBUILT_KERNEL, кладётся в
# дерево РУКАМИ и молча устаревает.  2026-09-03 там лежало ядро от 28
# августа — чистая сборка отгрузила бы ROM без единой правки того дня, и
# никакой инвентарь /system и /vendor этого не ловит: ядро в эти разделы
# не входит.  Правило, которое человек должен помнить, уже один раз не
# сработало; правило, которое валит сборку, не забывается.
#
# ГРАНИЦА ГЕЙТА, названная явно: он проверяет СООТВЕТСТВИЕ образа дереву,
# а НЕ актуальность дерева.  Зелёный ответ означает «образ совпадает с тем,
# что в дереве записано», а не «в дереве лежит нужное ядро».  2026-09-03
# дерево отстало на четыре ядра (#11 против #19 на аппарате), и гейт честно
# молчал — он и не должен был сработать.  Свежесть самого prebuilt —
# отдельный вопрос и отдельная ответственность.
#
#   $1 — путь к Image.gz-dtb
#   $2 — путь к файлу ожиданий (MD5 / VERSION)
set -u
IMG=$1
EXP=$2

# Подробности идут в stderr — make их не схлопывает, они видны в логе как
# есть, с переносами.  В stdout уходит короткий маркер, по которому
# BoardConfig валит сборку через $(error).
[ -f "$IMG" ] || { echo "ЯДРО НЕ НАЙДЕНО: $IMG" >&2; echo "prebuilt-kernel: ЯДРА НЕТ, см. подробности выше"; exit 0; }
[ -f "$EXP" ] || { echo "НЕТ ФАЙЛА ОЖИДАНИЙ: $EXP" >&2; echo "prebuilt-kernel: НЕТ ФАЙЛА ОЖИДАНИЙ, см. подробности выше"; exit 0; }

want_md5=$(awk '$1=="MD5"{print $2}' "$EXP")
have_md5=$(md5sum "$IMG" | cut -d' ' -f1)
[ "$want_md5" = "$have_md5" ] && exit 0

want_ver=$(sed -n 's/^VERSION //p' "$EXP")
have_ver=$(python3 - "$IMG" <<'PY' 2>/dev/null
import sys, zlib, re
d = open(sys.argv[1], 'rb').read()
i = d.find(b'\x1f\x8b\x08')
raw = b''
if i >= 0:
    try:
        raw = zlib.decompressobj(16 + zlib.MAX_WBITS).decompress(d[i:])
    except Exception:
        pass
m = re.search(rb'Linux version [0-9][^\x00]{0,120}', raw)
print(m.group(0).decode('utf-8', 'replace') if m else 'версию извлечь не удалось')
PY
)

cat >&2 <<MSG
ЯДРО В prebuilt-lane УСТАРЕЛО ИЛИ ПОДМЕНЕНО.
  файл:    $IMG
  ожидаем: $want_md5
           $want_ver
  найдено: $have_md5
           $have_ver
Что делать: собрать ядро из worktree k49-worktrees/piedisp (ветка pie-disp;
из pie-config собирать НЕЛЬЗЯ — там потерян SMI-фикс smi_legacy.c/mmsys_config),
затем сложить gzip -n -9 от arch/arm64/boot/Image с байт-в-байт стоковым DTB
captures/20260817-los-first-boot/dtb_stock.dtb (69427 Б) и положить сюда,
обновив $EXP.  Готовый помощник: tools/los16_repack_boot_kernel.sh.

ГРАНИЦА ЭТОГО ГЕЙТА: он не проверяет, что prebuilt АКТУАЛЕН.  Совпадение
md5 означает лишь «образ соответствует дереву»; отстало ли само дерево от
рабочего ядра — вопрос отдельный, и зелёный ответ на него не отвечает.
MSG
echo "prebuilt-kernel: ядро не совпадает с ожидаемым ($have_md5 вместо $want_md5), см. подробности выше"
